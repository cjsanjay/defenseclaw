        versions: set[int] = set()
        for path in transaction.EXACT_INTERNAL_OUTPUTS:
            payload = (repository / path).read_text(encoding="utf-8")
            if " = 1\n" in payload:
                versions.add(1)
            if " = 2\n" in payload:
                versions.add(2)
