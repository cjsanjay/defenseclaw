def _json_payload(version: int, role: str) -> bytes:
    return (
        '{\n  "x-defenseclaw-generated": {"generator": "telemetry-registry"},\n'
        f'  "role": "{role}",\n  "version": {version}\n}}\n'
    ).encode()


def _outputs(transaction: ModuleType, version: int, *, include_extra: bool = True) -> dict[str, Any]:
    rendered = transaction.RenderedOutput
    outputs = {
        transaction.MANIFEST_PATH: rendered(_json_payload(version, "manifest"), JSON_MARKER),
        "schemas/telemetry/generated/catalog.json": rendered(
            _json_payload(version, "catalog"),
            JSON_MARKER,
        ),
    }
    for index, path in enumerate(sorted(transaction.EXACT_INTERNAL_OUTPUTS)):
        outputs[path] = rendered(
            (
                "// Code generated by DefenseClaw telemetry registry; DO NOT EDIT.\n"
                f"package observability\n\nconst generatedVersion{index} = {version}\n"
            ).encode(),
            GO_MARKER,
        )
    if include_extra:
        outputs["schemas/telemetry/generated/otlp-fixtures/cases/case.json"] = rendered(
            _json_payload(version, "case"),
            JSON_MARKER,
        )
    return outputs


def _ownership(transaction: ModuleType, outputs: Mapping[str, Any]) -> dict[str, Any]:
    return {path: transaction.PriorOwnedOutput.from_rendered(output) for path, output in outputs.items()}


def _adoption_outputs(transaction: ModuleType, version: int) -> dict[str, Any]:
    outputs = _outputs(transaction, version, include_extra=False)
    for index, path in enumerate(sorted(transaction.EXACT_BASELINE_ADOPTION_PATHS)):
        outputs[path] = transaction.RenderedOutput(
            _json_payload(version, f"adopted-{index}"),
            JSON_MARKER,
        )
    return outputs


def _install_adoption_predecessors(
    transaction: ModuleType,
    repository: Path,
) -> tuple[dict[str, Any], dict[str, tuple[bytes, int]]]:
    adoption: dict[str, Any] = {}
    predecessors: dict[str, tuple[bytes, int]] = {}
    for index, path in enumerate(sorted(transaction.EXACT_BASELINE_ADOPTION_PATHS)):
        payload = (
            json.dumps(
                {"legacy": True, "ordinal": index, "path": path},
                sort_keys=True,
                separators=(",", ":"),
            )
            + "\n"
        ).encode()
        target = repository / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)
        target.chmod(0o644)
        adoption[path] = transaction.BaselineAdoption(
            payload=payload,
            sha256=hashlib.sha256(payload).hexdigest(),
            absent_marker=JSON_MARKER,
        )
        predecessors[path] = (payload, 0o644)
    return adoption, predecessors


def _continued_adoption_authority(transaction: ModuleType) -> dict[str, Any]:
    return {path: transaction.ContinuedAdoptionAuthority() for path in transaction.EXACT_BASELINE_ADOPTION_PATHS}


def _assert_adoption_predecessors(
    repository: Path,
    predecessors: Mapping[str, tuple[bytes, int]],
) -> None:
    for path, (payload, mode) in predecessors.items():
        target = repository / path
        assert target.read_bytes() == payload
        assert stat.S_IMODE(target.stat().st_mode) == mode


def _worktree_snapshot(root: Path) -> dict[str, tuple[bytes, int]]:
    result: dict[str, tuple[bytes, int]] = {}
    for base in (root / "schemas", root / "internal"):
        for path in base.rglob("*"):
            if path.is_file() and not path.is_symlink():
                result[path.relative_to(root).as_posix()] = (
                    path.read_bytes(),
                    stat.S_IMODE(path.stat().st_mode),
                )
    return result


def _assert_outputs(root: Path, outputs: Mapping[str, Any]) -> None:
    for path, output in outputs.items():
        target = root / path
        assert target.read_bytes() == output.payload
        assert stat.S_IMODE(target.stat().st_mode) == output.mode


def _worktree_repository(tmp_path: Path) -> Path:
    root = tmp_path / "linked-worktree"
    (root / "schemas/telemetry/generated").mkdir(parents=True)
    (root / "internal/observability").mkdir(parents=True)
    return root


def test_baseline_adoption_uses_the_exact_reviewed_26_path_authority_and_then_normal_ownership(
    transaction: ModuleType,
    repository: Path,
) -> None:
    assert len(transaction.EXACT_BASELINE_ADOPTION_PATHS) == 26
    adoption, _predecessors = _install_adoption_predecessors(transaction, repository)
    first = _adoption_outputs(transaction, 1)

    transaction.write_outputs(repository, first, {}, adoption=adoption)
    _assert_outputs(repository, first)
    continued = _continued_adoption_authority(transaction)
    transaction.check_outputs(repository, first, _ownership(transaction, first), adoption=continued)

    second = _adoption_outputs(transaction, 2)
    transaction.write_outputs(
        repository,
        second,
        _ownership(transaction, first),
        adoption=continued,
    )
    _assert_outputs(repository, second)
    transaction.check_outputs(repository, second, _ownership(transaction, second), adoption=continued)

    continued_evidence = next(iter(continued.values()))
    assert continued_evidence.__slots__ == ()
    assert not hasattr(continued_evidence, "payload")
    assert not hasattr(continued_evidence, "sha256")
    with pytest.raises(TypeError):
        transaction.ContinuedAdoptionAuthority(b"legacy bytes")


def test_baseline_adoption_rejects_wrong_same_count_path_substitution_before_writes(
    transaction: ModuleType,
    repository: Path,
) -> None:
    adoption, _predecessors = _install_adoption_predecessors(transaction, repository)
    before = _worktree_snapshot(repository)
    removed = sorted(adoption)[0]
    replacement = "schemas/not-a-reviewed-public-schema.json"
    substituted = dict(adoption)
    substituted[replacement] = substituted.pop(removed)

    with pytest.raises(transaction.TransactionError, match="outside the exact reviewed allowlist"):
        transaction.write_outputs(
            repository,
            _adoption_outputs(transaction, 1),
            {},
            adoption=substituted,
        )

    assert _worktree_snapshot(repository) == before


def test_baseline_adoption_rejects_partial_or_disappearing_authority(
    transaction: ModuleType,
    repository: Path,
) -> None:
    adoption, _predecessors = _install_adoption_predecessors(transaction, repository)
    outputs = _adoption_outputs(transaction, 1)
    omitted = sorted(adoption)[0]

    partial = dict(adoption)
    partial.pop(omitted)
    with pytest.raises(transaction.TransactionError, match="exact 26-path set"):
        transaction.write_outputs(repository, outputs, {}, adoption=partial)

    missing_desired = dict(outputs)
    missing_desired.pop(omitted)
    with pytest.raises(transaction.TransactionError, match="authority cannot disappear"):
        transaction.write_outputs(repository, missing_desired, {}, adoption=adoption)

    transaction.write_outputs(repository, outputs, {}, adoption=adoption)
    partial_prior = {omitted: _ownership(transaction, outputs)[omitted]}
    with pytest.raises(transaction.TransactionError, match="zero adoption paths"):
        transaction.write_outputs(repository, outputs, partial_prior, adoption=adoption)
    continued = _continued_adoption_authority(transaction)
    with pytest.raises(transaction.TransactionError, match="all adoption paths"):
        transaction.write_outputs(repository, outputs, partial_prior, adoption=continued)
    missing_repeat_desired = dict(outputs)
    missing_repeat_desired.pop(omitted)
    with pytest.raises(transaction.TransactionError, match="authority cannot disappear"):
        transaction.write_outputs(
            repository,
            missing_repeat_desired,
            _ownership(transaction, outputs),
            adoption=continued,
        )
    with pytest.raises(transaction.TransactionError, match="outside the allowlist"):
        transaction.write_outputs(repository, outputs, _ownership(transaction, outputs))


def test_adoption_modes_reject_mixed_or_wrong_phase_evidence_before_writes(
    transaction: ModuleType,
    repository: Path,
) -> None:
    baseline, _predecessors = _install_adoption_predecessors(transaction, repository)
    outputs = _adoption_outputs(transaction, 1)
    before = _worktree_snapshot(repository)
    continued = _continued_adoption_authority(transaction)
    mixed = dict(baseline)
    mixed[sorted(mixed)[0]] = transaction.ContinuedAdoptionAuthority()

    with pytest.raises(transaction.TransactionError, match="cannot mix baseline and continued"):
        transaction.write_outputs(repository, outputs, {}, adoption=mixed)
    with pytest.raises(transaction.TransactionError, match="all adoption paths"):
        transaction.write_outputs(repository, outputs, {}, adoption=continued)
    assert _worktree_snapshot(repository) == before

    transaction.write_outputs(repository, outputs, {}, adoption=baseline)
    generated = _worktree_snapshot(repository)
    with pytest.raises(transaction.TransactionError, match="zero adoption paths"):
        transaction.write_outputs(
            repository,
            _adoption_outputs(transaction, 2),
            _ownership(transaction, outputs),
            adoption=baseline,
        )
    assert _worktree_snapshot(repository) == generated


@pytest.mark.parametrize("mutation", ["bytes", "mode", "symlink", "hardlink"])
def test_baseline_adoption_authenticates_each_regular_single_link_predecessor(
    transaction: ModuleType,
    repository: Path,
    mutation: str,
) -> None:
    adoption, _predecessors = _install_adoption_predecessors(transaction, repository)
    path = sorted(adoption)[0]
    target = repository / path
    if mutation == "bytes":
        target.write_bytes(b"changed legacy bytes\n")
    elif mutation == "mode":
        target.chmod(0o600)
    elif mutation == "symlink":
        target.unlink()
        outside = repository.parent / "adoption-outside"
        outside.write_bytes(adoption[path].payload)
        target.symlink_to(outside)
    else:
        outside = repository.parent / "adoption-hardlink"
        outside.write_bytes(adoption[path].payload)
        target.unlink()
        os.link(outside, target)

    before = _worktree_snapshot(repository)
    with pytest.raises(transaction.TransactionError):
        transaction.write_outputs(
            repository,
            _adoption_outputs(transaction, 1),
            {},
            adoption=adoption,
        )
    assert _worktree_snapshot(repository) == before


