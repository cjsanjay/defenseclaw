def test_linked_worktree_gitfile_rejects_same_length_in_place_rewrite(
    transaction: ModuleType,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    repository = _worktree_repository(tmp_path)
    (repository / ".worktree-a").mkdir()
    (repository / ".worktree-b").mkdir()
    gitfile = repository / ".git"
    original_payload = b"gitdir: .worktree-a\n"
    replacement_payload = b"gitdir: .worktree-b\n"
    assert len(original_payload) == len(replacement_payload)
    gitfile.write_bytes(original_payload)
    before = _worktree_snapshot(repository)
    original = transaction.os.read
    rewritten = False

